class Command(BaseCommand):
    help = "Създава примерни вратички на български (до последния ден от настройките на календара)."

    def add_arguments(self, parser):
        parser.add_argument(
            "--force",
            action="store_true",
            help="Презаписва и вече съществуващите вратички.",
        )

    @transaction.atomic
    def handle(self, *args, force=False, **options):
        cfg = AdventSettings.load()
        created = updated = skipped = 0

        for day, (door_type, title, text, answer) in enumerate(SAMPLE_DOORS[: cfg.last_day], start=1):
            values = {
                "type": door_type,
                "title": title,
                "text": text,
                "answer": answer,
                "is_published": True,
            }
            if force:
                _, was_created = Door.objects.update_or_create(day=day, defaults=values)
                if was_created:
                    created += 1
                else:
                    updated += 1
            else:
                _, was_created = Door.objects.get_or_create(day=day, defaults=values)
                if was_created:
                    created += 1
                else:
                    skipped += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Готово: създадени {created}, обновени {updated}, пропуснати {skipped} (последен ден: {cfg.last_day})."
            )
        )
        if skipped:
            self.stdout.write("Използвай --force, за да презапишеш съществуващите вратички.")
