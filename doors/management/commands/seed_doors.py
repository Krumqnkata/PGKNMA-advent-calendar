CONTENT_FIELDS = ("type", "title", "text", "answer", "image_credit", "image_source")


def apply_sample(door, data):
    """Записва примерното съдържание (включително снимката) във вратичката."""
    for field in CONTENT_FIELDS:
        setattr(door, field, data.get(field, ""))
    door.is_published = True
    if door.image:
        door.image.delete(save=False)
    if data.get("image"):
        with open(SEED_IMAGES / data["image"], "rb") as fh:
            door.image.save(data["image"], File(fh), save=False)
    door.save()


class Command(BaseCommand):
    help = "Създава примерни вратички на български (до последния ден от настройките на календара)."

    def add_arguments(self, parser):
        parser.add_argument(
            "--force",
            action="store_true",
            help="Презаписва и вече съществуващите вратички (текст, тип и снимка).",
        )

    @transaction.atomic
    def handle(self, *args, force=False, **options):
        cfg = AdventSettings.load()
        created = updated = skipped = 0

        for day, data in enumerate(SAMPLE_DOORS[: cfg.last_day], start=1):
            door = Door.objects.filter(day=day).first()
            if door is None:
                apply_sample(Door(day=day), data)
                created += 1
            elif force:
                apply_sample(door, data)
                updated += 1
            else:
                skipped += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Готово: създадени {created}, обновени {updated}, пропуснати {skipped} (последен ден: {cfg.last_day})."
            )
        )
        if skipped:
            self.stdout.write("Използвай --force, за да презапишеш съществуващите вратички.")
